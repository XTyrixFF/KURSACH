// Импортируем React (не обязательно в новых версиях, но полезно для единообразия)
import React from 'react';
// 3.1 Переиспользование кода: импортируем наш кастомный хук для получения данных
import { useAnimals } from '../hooks/useAnimals';
// Импортируем компонент карточки животного
import AnimalCard from '../features/animals/AnimalCard';

// Главная страница приложения
const HomePage = () => {
  // Используем кастомный хук. Он сам сделает запрос к Redux (если нужно) 
  // и вернет нам массив животных и текущий статус загрузки.
  const { animals, status } = useAnimals();

  // Условный рендеринг (Conditional Rendering). 
  // Если данные еще грузятся (status === 'loading'), показываем текст загрузки и прерываем рендер (return).
  if (status === 'loading') return <h2>Загрузка животных...</h2>;

  return (
    // Обертка страницы с внутренним отступом (inline-стили)
    <div style={{ padding: '20px' }}>
      
      <h1>Добро пожаловать в наш Зоопарк!</h1>
      
      {/* Контейнер для сетки. Используем Flexbox для кроссбраузерной и адаптивной верстки (п. 3.4) */}
      <div style={{ display: 'flex', flexWrap: 'wrap', gap: '20px' }}>
        
        {/* 3.1 Связь с DOM: keys. 
            Метод .map() перебирает массив животных и создает для каждого компонент <AnimalCard />.
            Свойство key={animal.id} КРИТИЧЕСКИ ВАЖНО для React. 
            Оно помогает виртуальному DOM (Virtual DOM) понять, какая именно карточка изменилась, 
            удалилась или добавилась. Без key React будет перерисовывать весь список целиком, что медленно. */}
        {animals.map((animal) => (
          // Передаем данные конкретного животного в пропс (props) компонента карточки
          <AnimalCard key={animal.id} animal={animal} />
        ))}
        
      </div>
    </div>
  );
};

// Экспортируем компонент для использования в App.jsx
export default HomePage;